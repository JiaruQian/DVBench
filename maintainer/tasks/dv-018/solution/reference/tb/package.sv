class dvbench_scoreboard extends uvm_component;
    uvm_analysis_imp#(dvbench_transaction,dvbench_scoreboard) observations;
    longint checked_points, mismatched_points;
    `uvm_component_utils(dvbench_scoreboard)
    covergroup response_coverage with function sample(integer ones, bit mismatch);
        option.per_instance=1;
        response_bits: coverpoint ones { bins zero={0}; bins nonzero={[1:4096]}; }
        comparison: coverpoint mismatch { bins correct={0}; bins incorrect={1}; }
    endgroup
    function new(string name,uvm_component parent);
        super.new(name,parent); observations=new("observations",this); response_coverage=new();
    endfunction
    function void write(dvbench_transaction observed);
        bit mismatch;
        mismatch=(observed.actual_state & observed.compare_mask) !== (observed.expected_state & observed.compare_mask);
        if($isunknown(observed.expected_state & observed.compare_mask)) mismatch=1;
        checked_points++;
        response_coverage.sample($countones(observed.expected_state & observed.compare_mask),mismatch);
        if(mismatch) begin
            mismatched_points++;
            if(mismatched_points<=20) `uvm_error("PORT_MISMATCH",$sformatf("point=%0d actual=%h expected=%h mask=%h",checked_points,observed.actual_state,observed.expected_state,observed.compare_mask))
        end
    endfunction
    function void check_phase(uvm_phase phase);
        super.check_phase(phase);
        if(checked_points==0) `uvm_error("VACUOUS","No sampled comparisons")
        `uvm_info("CHECK_COUNTS",$sformatf("points=%0d mismatches=%0d",checked_points,mismatched_points),UVM_NONE)
    endfunction
    function void report_phase(uvm_phase phase);
        super.report_phase(phase);
        if(checked_points>0 && mismatched_points==0 && uvm_report_server::get_server().get_severity_count(UVM_ERROR)==0 && uvm_report_server::get_server().get_severity_count(UVM_FATAL)==0)
            $display("DVBench_COMPLETED");
    endfunction
endclass
