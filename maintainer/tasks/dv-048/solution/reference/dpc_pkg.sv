  // ---------- Sequence library (≥1 directed stimuli per feature) ----------
  class seq_base extends uvm_sequence #(dpc_txn);
    `uvm_object_utils(seq_base)
    function new(string n = "seq_base"); super.new(n); endfunction
    task fr(scn_e scn, bit fmt, bit [7:0] thr, int nl, int np, int gap, int vblk, int seed);
      dpc_txn t = dpc_txn::type_id::create("t");
      start_item(t);
      void'(t.randomize());
      t.scn = scn; t.fmt = fmt; t.thr = thr;          // Override directly with directed values (avoid solver conflicts)
      t.n_lines = nl; t.n_pix = np; t.gap = gap; t.vblk = vblk; t.seed = seed ^ $urandom();
      if(scn==SCN_WITNESS) t.seed=seed;
      finish_item(t);
    endtask
  endclass

