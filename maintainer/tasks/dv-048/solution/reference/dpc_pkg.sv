// dpc_pkg.sv — dpc_5x5 UVM environment (Bayer-aware defective pixel correction, purely streaming with no handshake)
// feature index: F01 Reset F02 Synchronization protocol F03 bayer_format/row parity F04 Threshold
//               F05 Data value categories F06 Correction decision/polarity F07 Flow control(D spacing/back-to-back)
//               F08 Stream order 1:1 cycle-by-cycle matching F09 Coverage(all covergroup dimensions)
`timescale 1ns/1ps
package dpc_pkg;
  import uvm_pkg::*;
  `include "uvm_macros.svh"

  typedef enum int {
    SCN_SMOOTH, SCN_DEFECT, SCN_TIES, SCN_BOUND, SCN_RANDOM,
    SCN_THR_SWEEP, SCN_MIXSIG, SCN_XINJECT, SCN_GAP, SCN_RESET, SCN_WITNESS
  } scn_e;

  // ---------- Observation transaction (monitor samples once every negedge: input nets + DUT output) ----------
  class dpc_obs extends uvm_object;
    logic        rst_n;
    logic        bfmt;
    logic [7:0]  thr;
    logic [2:0]  syn;
    logic [7:0]  d [5];
    logic [7:0]  odata;
    logic [2:0]  osync;
    `uvm_object_utils(dpc_obs)
    function new(string name = "dpc_obs"); super.new(name); endfunction
  endclass

  // ---------- Stimulus transaction (one-frame description) ----------
  class dpc_txn extends uvm_sequence_item;
    rand scn_e    scn;
    rand bit      fmt;
    rand bit [7:0] thr;
    rand int      n_lines;
    rand int      n_pix;
    rand int      gap;
    rand int      vblk;
    rand int      seed;
    constraint c_dflt {
      n_lines inside {[2:8]}; n_pix inside {[16:40]};
      gap inside {[0:12]}; vblk inside {[2:16]};
    }
    `uvm_object_utils_begin(dpc_txn)
      `uvm_field_int(scn, UVM_ALL_ON) `uvm_field_int(fmt, UVM_ALL_ON)
      `uvm_field_int(thr, UVM_ALL_ON) `uvm_field_int(n_lines, UVM_ALL_ON)
      `uvm_field_int(n_pix, UVM_ALL_ON) `uvm_field_int(gap, UVM_ALL_ON)
    `uvm_object_utils_end
    function new(string name = "dpc_txn"); super.new(name); endfunction
  endclass

  // ---------- monitor (samples at negedge+0.5ns, avoiding rst_n/driving races) ----------
  class dpc_mon extends uvm_monitor;
    `uvm_component_utils(dpc_mon)
    virtual dpc_if vif;
    uvm_analysis_port #(dpc_obs) ap;
    function new(string name, uvm_component parent);
      super.new(name, parent); ap = new("ap", this);
    endfunction
    function void build_phase(uvm_phase phase);
      super.build_phase(phase);
      if (!uvm_config_db#(virtual dpc_if)::get(this, "", "vif", vif))
        `uvm_fatal("NOVIF", "vif is not configured")
    endfunction
    task run_phase(uvm_phase phase);
      dpc_obs o;
      forever begin
        @(negedge vif.clk);
        #0.5;                      // Offset from the interface's rst_n procedural assignment on the same edge
        o = dpc_obs::type_id::create("o");
        o.rst_n = vif.rst_n;
        o.bfmt  = vif.bayer_format;
        o.thr   = vif.i_dpc_threshold;
        o.syn   = vif.i_video_syn;
        o.d[0]  = vif.i_data_r0; o.d[1] = vif.i_data_r1; o.d[2] = vif.i_data_r2;
        o.d[3]  = vif.i_data_r3; o.d[4] = vif.i_data_r4;
        o.odata = vif.o_data;
        o.osync = vif.o_video_sync;
        ap.write(o);
      end
    endtask
  endclass

  // ---------- driver (frame-level stimulus: V idle→frame start→D rise/pixels/D fall/gap for each row) ----------
  class dpc_drv extends uvm_driver #(dpc_txn);
    `uvm_component_utils(dpc_drv)
    virtual dpc_if vif;
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
    function void build_phase(uvm_phase phase);
      super.build_phase(phase);
      if (!uvm_config_db#(virtual dpc_if)::get(this, "", "vif", vif))
        `uvm_fatal("NOVIF", "vif is not configured")
    endfunction
    task run_phase(uvm_phase phase);
      dpc_txn t;
      repeat (2) @(vif.cb);       // No driving initially: inputs remain X (feed the mid_3x3 case default branch)
      forever begin
        seq_item_port.get_next_item(t);
        drive_frame(t);
        seq_item_port.item_done();
      end
    endtask
    function automatic logic [7:0] rnd8(ref bit [31:0] s);
      s = s * 32'd1664525 + 32'd1013904223;
      return s[15:8];
    endfunction
    // Single-pixel 5-row values (generated by scenario; defect/boundary/X injections are all deterministic)
    function void drive_pix(dpc_txn t, int li, int pi, ref bit [31:0] s);
      logic [7:0] v [5];
      logic [7:0] base, mag;
      bit [7:0] thr_lut [8] = '{8'd0, 8'd1, 8'd15, 8'd16, 8'd127, 8'd128, 8'd254, 8'd255};
      int gap_lut [6] = '{1, 4, 12, 2, 6, 0};
      case (t.scn)
        SCN_SMOOTH, SCN_RESET: begin
          for (int r = 0; r < 5; r++)
            v[r] = 8'd60 + ((pi * 2) / 3) % 8'd40 + ((li * 5 + r * 2) % 7);
          if (t.scn == SCN_RESET && (pi % 12) == 8 && li[0])
            v[2] = li[1] ? 8'd220 : 8'd20;          // The mid-row reset scenario also includes defects
        end
        SCN_DEFECT: begin
          if (li[0]) begin                                // Dark defective pixel row: all 255 + sparse dark pixels
            for (int r = 0; r < 5; r++) v[r] = 8'd255;
            if ((pi % 12) == 8) begin
              if (pi == 20) v[0] = 8'd60;                 // Defect at a neighborhood position (perturbation)
              else v[2] = 8'd60;                          // delta=-195(>128)→wraps around to 61, sig==00 triggers
            end
          end else begin                                  // Bright defective pixel row: all 100 + sparse bright pixels
            base = 8'd100;
            for (int r = 0; r < 5; r++) v[r] = base;
            mag = t.thr + 8'd24;                          // delta=+thr+24>thr triggers
            if ((pi % 12) == 8) begin
              if (pi == 20) v[0] = (base + mag > 8'd255) ? 8'd255 : base + mag;
              else v[2] = (base + mag > 8'd255) ? 8'd255 : base + mag;
            end
          end
        end
        SCN_TIES: begin
          base = (li < 2) ? 8'h80 : ((li < 4) ? 8'hC0 : 8'hA0);
          for (int r = 0; r < 5; r++)
            v[r] = (li >= 4) ? ((pi < t.n_pix / 2) ? 8'h80 : 8'hC0) : base;
        end
        SCN_BOUND: begin
          for (int r = 0; r < 5; r++)
            v[r] = (pi < 8) ? 8'h00 : ((pi < 16) ? 8'hFF : (pi[0] ? 8'h00 : 8'hFF));
        end
        SCN_RANDOM, SCN_WITNESS: for (int r = 0; r < 5; r++) v[r] = rnd8(s);
        SCN_THR_SWEEP: begin
          base = 8'd128;
          for (int r = 0; r < 5; r++) v[r] = base;
          if (pi == 8)                              // |d|==thr boundary: does not trigger correction
            v[2] = (base > thr_lut[li % 8]) ? base - thr_lut[li % 8] : base;
          if (pi == 16)                             // |d|==thr+1: triggers correction
            v[2] = (base + thr_lut[li % 8] + 1 > 8'd255) ? 8'd0
                        : base + thr_lut[li % 8] + 1;
        end
        SCN_MIXSIG: begin
          // Column values traverse 60→100→150→100 over 4 cycles (the middle three rows have identical values, edge rows are constantly 100): any window
          // extraction (center column or column±1) will simultaneously mix neighbors <100 and >100 → positive/negative differences coexist,
          // sig==8'h0f hits the second term of RTL comp_en
          for (int r = 0; r < 5; r++) v[r] = 8'd100;
          case (pi % 4)
            0: begin v[1]=8'd60;  v[2]=8'd60;  v[3]=8'd60;  end
            1: begin v[1]=8'd100; v[2]=8'd100; v[3]=8'd100; end
            2: begin v[1]=8'd150; v[2]=8'd150; v[3]=8'd150; end
            3: begin v[1]=8'd100; v[2]=8'd100; v[3]=8'd100; end
          endcase
        end
        SCN_XINJECT: begin
          for (int r = 0; r < 5; r++) v[r] = 8'd70 + (pi % 8'd20);
          if (pi >= 10 && pi <= 17)
            for (int r = 0; r < 5; r++) v[r] = 8'hXX;  // X injection (default branch + X propagation)
        end
        SCN_GAP: for (int r = 0; r < 5; r++) v[r] = 8'd90 + ((pi / 3) % 8'd16) + r;
        default: for (int r = 0; r < 5; r++) v[r] = 8'd80;
      endcase
      vif.cb.i_data_r0 <= v[0]; vif.cb.i_data_r1 <= v[1]; vif.cb.i_data_r2 <= v[2];
      vif.cb.i_data_r3 <= v[3]; vif.cb.i_data_r4 <= v[4];
    endfunction
    function automatic int gap_of(dpc_txn t, int li);
      int gap_lut [6] = '{1, 4, 12, 2, 6, 0};
      if (t.scn == SCN_GAP) return gap_lut[li % 6];
      return t.gap;
    endfunction
    task drive_frame(dpc_txn t);
      bit [31:0] s = t.seed;
      bit [7:0] thr_lut [8] = '{8'd0, 8'd1, 8'd15, 8'd16, 8'd127, 8'd128, 8'd254, 8'd255};
      vif.cb.bayer_format  <= t.fmt;
      vif.cb.i_dpc_threshold <= t.thr;
      vif.cb.i_video_syn <= 3'b100;                 // V idle period (V=1,D=0)
      vif.cb.i_data_r0 <= 8'h00; vif.cb.i_data_r1 <= 8'h00;
      vif.cb.i_data_r2 <= 8'h00; vif.cb.i_data_r3 <= 8'h00; vif.cb.i_data_r4 <= 8'h00;
      repeat (t.vblk) @(vif.cb);
      vif.cb.i_video_syn <= 3'b101;                 // H=1 during the idle period (syn combination coverage)
      repeat (2) @(vif.cb);
      vif.cb.i_video_syn <= 3'b001;                 // V falling edge (H remains 1 for the transition cycle)
      @(vif.cb);
      vif.cb.i_video_syn <= 3'b000;                 // Frame start
      repeat (2) @(vif.cb);
      for (int li = 0; li < t.n_lines; li++) begin
        int npl = (t.scn == SCN_GAP && li == 3) ? 10 : t.n_pix;  // Short row: small drun bin
        if (t.scn == SCN_THR_SWEEP) vif.cb.i_dpc_threshold <= thr_lut[li % 8];
        vif.cb.i_video_syn <= {1'b0, 1'b1, li[0]};  // D rises, H toggles row by row
        for (int pi = 0; pi < npl; pi++) begin
          drive_pix(t, li, pi, s);
          if (t.scn == SCN_GAP && li == 4 && pi == 4)
            vif.cb.i_video_syn <= 3'b110;           // V=1&D=1&H=0 illegal combination (coverage only)
          if (t.scn == SCN_GAP && li == 4 && pi == 6)
            vif.cb.i_video_syn <= 3'b111;           // V=1&D=1&H=1 illegal combination (coverage only)
          if (t.scn == SCN_GAP && li == 4 && pi == 8)
            vif.cb.i_video_syn <= {1'b0, 1'b1, li[0]};
          @(vif.cb);
          if (t.scn == SCN_RESET && li == 2 && pi == t.n_pix / 2)
            vif.pulse_reset();                      // Reset during an active line (F01)
        end
        vif.cb.i_video_syn <= 3'b001;               // D falls (H=1 for one cycle)
        @(vif.cb);
        vif.cb.i_video_syn <= 3'b000;
        repeat (gap_of(t, li)) @(vif.cb);
      end
      vif.cb.i_video_syn <= 3'b100;                 // V returns high (end of frame)
      repeat (4) @(vif.cb);
    endtask
  endclass


  class dpc_sb extends uvm_scoreboard;
    `uvm_component_utils(dpc_sb)
    uvm_analysis_imp #(dpc_obs,dpc_sb) imp;
    virtual dpc_if vif;
    int settling=0,compared=0,errors=0;
    bit q_format; bit[7:0] q_thr; bit[2:0] q_syn;
    covergroup cg;
      cp_format:coverpoint q_format;
      cp_threshold:coverpoint q_thr {bins zero={0};bins near0={1};bins mid={[2:253]};bins nearmax={254};bins max={255};}
      cp_sync:coverpoint q_syn;
      cross cp_format,cp_threshold;
    endgroup
    function new(string n,uvm_component p);super.new(n,p);imp=new("imp",this);cg=new();endfunction
    function void build_phase(uvm_phase phase);
      if(!uvm_config_db#(virtual dpc_if)::get(this,"","vif",vif)) `uvm_fatal("NOVIF","missing interface")
    endfunction
    function void write(dpc_obs o);
      if(!o.rst_n) settling=0; else settling++;
      if(settling>=16) begin
        compared++;
        if(o.odata!==vif.expected_data || o.osync!==vif.expected_sync) begin
          errors++;
          if(errors<=12) `uvm_error("DPC_COMPARE",$sformatf("point=%0d actual=%h/%b expected=%h/%b",compared,o.odata,o.osync,vif.expected_data,vif.expected_sync))
        end
      end
      q_format=o.bfmt;q_thr=o.thr;q_syn=o.syn;cg.sample();
    endfunction
    function void report_phase(uvm_phase phase);
      uvm_report_server server=uvm_report_server::get_server();
      if(compared<100) `uvm_error("VACUOUS","fewer than 100 actual comparisons")
      `uvm_info("DPC_COUNTS",$sformatf("compared=%0d mismatches=%0d",compared,errors),UVM_LOW)
      if(compared>=100 && errors==0 && server.get_severity_count(UVM_ERROR)==0 && server.get_severity_count(UVM_FATAL)==0)
        $display("DVBench_COMPLETED");
    endfunction
  endclass
